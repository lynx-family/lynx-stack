// The Rsbuild plugin that does the kit's own steps of the build, all from the
// same layout:
//
// - replaces the content of src/registered.ts with the registered modules;
// - rewrites every bundled module: the functions of `stringified` files keep
//   their published text, then the module gets its virtual location;
// - emits `mirror.json` from the modules of the compilation;
// - keeps only the kit's own build-time constants.

import path from 'node:path';

import type { RsbuildPlugin } from '@rsbuild/core';

import type { Layout } from './layout.ts';
import { collectMirror } from './mirror.ts';
import { isInside, pathKey, relativeSpecifier } from './paths.ts';
import { keepFunctionText } from './verbatim-functions.ts';
import { setVirtualLocation } from './virtual-paths.ts';

export interface PluginWebBundleKitOptions {
  /** The virtual `node_modules` tree. */
  layout: Layout;
  /**
   * The stub module whose content becomes the registered modules, and the
   * real paths of those modules.
   */
  registered: { stub: string; files: string[] };
  /** Real paths of the modules whose functions keep their published text. */
  stringified: string[];
  /**
   * Directories whose modules keep their real location: the kit's own code
   * and what it loads from next to itself at run time.
   */
  keepLocation: string[];
  /**
   * The only constants replaced at build time. They take the place of
   * Rsbuild's defaults (`import.meta.env.*`, `process.env.BASE_URL`,
   * `process.env.ASSET_PREFIX` and the `PUBLIC_*` variables of the building
   * machine): the bundled toolchain reads its environment at run time.
   */
  define: Record<string, string>;
}

const SCRIPT = /\.[cm]?js$/;

/** The source of the registered modules, imported relatively from `stub`. */
export function registeredSource(
  stub: string,
  files: string[],
  layout: Layout,
): string {
  const dir = path.dirname(stub);
  return [
    '// Generated by the web-bundle-kit Rsbuild plugin.',
    'export const registered = {',
    ...files.map((file) => {
      const virtual = layout.toVirtual(file);
      if (!virtual) {
        throw new Error(`${file} is not in the virtual node_modules tree`);
      }
      // Relative, so that the output does not depend on where the
      // repository is checked out.
      return `  ${JSON.stringify(virtual)}: () => import(${
        JSON.stringify(relativeSpecifier(dir, file))
      }),`;
    }),
    '};',
    '',
  ].join('\n');
}

export function pluginWebBundleKit(
  options: PluginWebBundleKitOptions,
): RsbuildPlugin {
  const { layout, registered, stringified, keepLocation, define } = options;
  // Rspack's resource paths may spell a path differently from Node.js on
  // Windows (the case of the drive letter, for one), so paths are compared
  // through `pathKey` and `isInside`.
  const stringifiedKeys = new Set(stringified.map((file) => pathKey(file)));
  const registeredCode = registeredSource(
    registered.stub,
    registered.files,
    layout,
  );

  return {
    name: 'web-bundle-kit',
    setup(api) {
      api.modifyBundlerChain({
        order: 'post',
        handler: (chain, { CHAIN_ID }) => {
          chain.plugin(CHAIN_ID.PLUGIN.DEFINE).tap(() => [define]);
        },
      });

      api.transform(
        {
          test: (resource: string) =>
            pathKey(resource) === pathKey(registered.stub),
          order: 'pre',
        },
        () => registeredCode,
      );

      // One transform, so that the order is fixed: the verbatim rewrite must
      // see the published text, and the location rewrite changes it.
      api.transform(
        {
          test: (resource: string) =>
            SCRIPT.test(resource)
            && !keepLocation.some((dir) => isInside(resource, dir)),
          order: 'pre',
        },
        ({ code, resourcePath }) => {
          const kept = stringifiedKeys.has(pathKey(resourcePath))
            ? keepFunctionText(code, resourcePath)
            : code;
          const located = setVirtualLocation(kept, resourcePath, layout);
          if (located === undefined) {
            api.logger.warn(
              `${resourcePath} uses its own location but its package is not in the virtual node_modules tree`,
            );
            return kept;
          }
          return located;
        },
      );

      api.processAssets(
        { stage: 'additional' },
        ({ compilation, sources }) => {
          if (compilation.errors.length > 0) return;
          const bundled = new Set<string>();
          for (const module of compilation.modules) {
            const resource = (module as { resource?: string }).resource
              ?.split('?')[0];
            if (resource) bundled.add(resource);
          }
          const bundledKeys = new Set(
            [...bundled].map((file) => pathKey(file)),
          );
          const unused = stringified.filter((file) =>
            !bundledKeys.has(pathKey(file))
          );
          if (unused.length > 0) {
            throw new Error(
              `STRINGIFIED lists files the kit does not bundle (stale entries, or the plugin moved them):\n  ${
                unused.join('\n  ')
              }`,
            );
          }
          const mirror = collectMirror({ layout, bundled });
          compilation.emitAsset(
            'mirror.json',
            new sources.RawSource(JSON.stringify(mirror)),
          );
          api.logger.info(
            `mirror.json: ${Object.keys(mirror.files).length} files`,
          );
        },
      );
    },
  };
}
